// Deterministic blog content shared by every framework's app: the same posts, byte for byte,
// so the only thing that differs between apps is the framework.

const WORDS =
  "wind gale gust breeze storm front pressure island harbor ridge valley current tide signal route render stream cache layer bundle module server client page frame static dynamic chunk build deploy edge origin request response header token state patch event".split(
    " ",
  );

function rng(seed) {
  let a = seed >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

function sentence(r, min, max) {
  const n = min + Math.floor(r() * (max - min + 1));
  const words = Array.from({ length: n }, () => WORDS[Math.floor(r() * WORDS.length)]);
  words[0] = words[0][0].toUpperCase() + words[0].slice(1);
  return `${words.join(" ")}.`;
}

function paragraph(r) {
  return Array.from({ length: 3 + Math.floor(r() * 3) }, () => sentence(r, 6, 14)).join(" ");
}

// About 1.5 KB of Markdown per post: headings, paragraphs, a list, a code block and a link.
function body(r, i) {
  return [
    `## ${sentence(r, 3, 5).slice(0, -1)}`,
    paragraph(r),
    paragraph(r),
    `- ${sentence(r, 3, 6)}\n- ${sentence(r, 3, 6)}\n- ${sentence(r, 3, 6)}`,
    `## ${sentence(r, 2, 4).slice(0, -1)}`,
    paragraph(r),
    "```js\nexport function handler(req) {\n  return new Response(`post " + i + "`);\n}\n```",
    `${paragraph(r)} See [the index](/posts) for more.`,
  ].join("\n\n");
}

export function posts(n) {
  const r = rng(20261104);
  const start = Date.UTC(2026, 0, 1);
  return Array.from({ length: n }, (_, k) => {
    const i = k + 1;
    return {
      slug: `post-${String(i).padStart(4, "0")}`,
      title: `Post ${i}: ${sentence(r, 2, 4).slice(0, -1)}`,
      date: new Date(start + k * 86400000).toISOString().slice(0, 10),
      summary: sentence(r, 10, 16),
      body: body(r, i),
    };
  }).reverse();
}

// The posts as a JS/TS module. `typed` adds a type annotation for .ts files.
export function postsModule(n, typed = false) {
  const type = typed
    ? "export type Post = { slug: string; title: string; date: string; summary: string; body: string };\n\nexport const posts: Post[] = "
    : "export const posts = ";
  return `// Generated by benchmarks/compare/gen.mjs (${n} posts). Do not edit.\n${type}${JSON.stringify(posts(n), null, 1)};\n`;
}
