// Links: every relative link on a generated page must point at a file that exists and, with a
// fragment, at a heading of a generated page.

function checkLinks(root, files) {
  const anchors = new Map();
  for (const [name, text] of files) {
    const set = new Set();
    const count = new Map();
    let fence = false;
    for (const l of text.split("\n")) {
      if (l.startsWith("```")) fence = !fence;
      const h = !fence && l.match(/^#{1,6} (.+)$/);
      if (!h) continue;
      const s = slug(h[1]);
      const n = count.get(s) ?? 0;
      count.set(s, n + 1);
      set.add(n ? `${s}-${n}` : s);
    }
    anchors.set(name, set);
  }
  const bad = [];
  for (const [name, text] of files) {
    const body = text.replace(/```[\s\S]*?```/g, "").replace(/`[^`\n]*`/g, "");
    for (const m of body.matchAll(/\]\(([^)\s]+)\)/g)) {
      const href = m[1];
      if (/^[a-z]+:/.test(href)) continue;
      const [file, frag] = href.split("#");
      const target = file ? path.posix.normalize(path.posix.join(OUT_DIR, file)) : `${OUT_DIR}/${name}`;
      const local = target.startsWith(`${OUT_DIR}/`) ? target.slice(OUT_DIR.length + 1) : null;
      if (local && files.has(local)) {
        if (frag && !anchors.get(local).has(frag)) bad.push(`${name}: ${href} (no such heading)`);
      } else if (!existsSync(path.join(root, target))) bad.push(`${name}: ${href} (no such file)`);
    }
  }
  if (bad.length) fail(`broken links:\n  ${bad.join("\n  ")}`);
}

