// Package pages

const PACKAGES = [
  { dir: "packages/nowaki-runtime", pkg: "@nowaki-dev/runtime", base: "runtime" },
  { dir: "packages/nowaki-markdoc", pkg: "@nowaki-dev/markdoc", base: "markdoc" },
];

/// The type-file pages: [{ page, pkg, subpath, specifier, file, sf, decl }].
function typePages(root) {
  const out = [];
  for (const p of PACKAGES) {
    const json = JSON.parse(read(root, `${p.dir}/package.json`));
    for (const sub of Object.keys(json.exports).sort()) {
      if (sub.includes("*")) continue;
      const file = `${p.dir}/${json.exports[sub].types.replace(/^\.\//, "")}`;
      const page = sub === "." ? `${p.base}.md` : `${p.base}-${sub.slice(2).replace(/\//g, "-")}.md`;
      const sf = parse(root, file);
      out.push({ page, pkg: p.pkg, subpath: sub, specifier: sub === "." ? p.pkg : `${p.pkg}/${sub.slice(2)}`, file, sf, decl: declarations(sf) });
    }
  }
  return out;
}

/// name → [{ page, anchor }] for every declaration on the type pages (exported ones first).
function symbolTable(pages) {
  const symbols = new Map();
  for (const p of pages) {
    const used = new Map();
    for (const item of p.decl.items) {
      let a = slug(item.name);
      const n = used.get(a) ?? 0;
      used.set(a, n + 1);
      if (n) a = `${a}-${n}`;
      item.anchor = a;
      if (!symbols.has(item.name)) symbols.set(item.name, []);
      symbols.get(item.name).push({ page: p.page, anchor: a, exported: item.exported });
    }
  }
  for (const list of symbols.values()) list.sort((x, y) => Number(y.exported) - Number(x.exported));
  return symbols;
}

/// A link resolver for `page`: a name on the same page wins, then an exported one elsewhere.
function linker(symbols, page) {
  const target = (name) => {
    const list = symbols.get(name);
    if (!list) return null;
    const t = list.find((x) => x.page === page) ?? list.find((x) => x.exported) ?? list[0];
    return t.page === page ? `#${t.anchor}` : `${t.page}#${t.anchor}`;
  };
  const link = (name, label) => {
    const base = name.split(".")[0];
    const t = target(base);
    return t ? `[${code(label || name)}](${t})` : code(label || name);
  };
  link.target = target;
  return link;
}

/// The printer writes a tuple type over several lines ("[\n    a: A\n]") and an empty body as
/// "{\n}"; keep those on one line.
const tightTuples = (s) => s.replace(/\{\n\}/g, "{}").replace(/\[\n\s*\]/g, "[]").replace(/\[\n\s*([^[\]\n]*)\n\s*\]/g, "[$1]");

function printDecl(item, sf) {
  return item.decls.map((d) => tightTuples(printer.printNode(ts.EmitHint.Unspecified, d, sf).trim())).join("\n");
}

function renderTypePage(p, symbols, usedBy) {
  const link = linker(symbols, p.page);
  const { items, reexports, defaultExport } = p.decl;
  const exported = items.filter((i) => i.exported);
  const local = items.filter((i) => !i.exported);
  const out = [
    NOTICE(`\`${p.file}\``),
    "",
    `# ${p.specifier}`,
    "",
    `${GENERATED} Source: [\`${p.file}\`](../../${p.file}). All of it is covered by semver ([STABILITY.md](../STABILITY.md)).`,
    "",
  ];
  const head = p.sf.statements.length ? ts.getLeadingCommentRanges(p.sf.text, 0) : null;
  const fileComment = head?.find((c) => p.sf.text.startsWith("//", c.pos));
  if (fileComment) {
    const lines = [];
    for (const c of head) if (p.sf.text.startsWith("//", c.pos)) lines.push(p.sf.text.slice(c.pos + 2, c.end).trim());
    out.push(inline(lines.join(" "), link), "");
  }
  if (exported.length || reexports.length) {
    const rows = exported.map((i) => [`[${code(i.name)}](#${i.anchor})`, KIND_LABEL[i.kind], inline(summary(i.doc), link)]);
    for (const r of reexports) rows.push([link(r.name), r.type ? "Type (re-export)" : "Re-export", `Re-exported from \`${r.from}\`.`]);
    if (defaultExport) rows.push(["`default`", "Default export", `The same as ${link(defaultExport)}.`]);
    out.push("## Exports", "", table(["Name", "Kind", "Summary"], rows), "");
  }
  const section = (item) => {
    const valueLike = ["function", "component", "class", "const"].includes(item.kind);
    const lines = [`### ${item.name}`, ""];
    const dep = deprecatedMarkdown(item.doc, link);
    if (dep) lines.push(dep, "");
    lines.push(
      item.exported
        ? `${KIND_LABEL[item.kind]}. \`import ${valueLike ? "" : "type "}{ ${item.name} } from "${p.specifier}";\``
        : `${KIND_LABEL[item.kind]}, not exported: listed because exported declarations use it.`,
      "",
    );
    lines.push("```ts", printDecl(item, p.sf), "```", "");
    if (item.doc?.lines.length) lines.push(docMarkdown(item.doc.lines, link), "");
    const st = item.decls[0];
    let members = [];
    if (ts.isInterfaceDeclaration(st) || ts.isClassDeclaration(st)) members = membersOf(p.sf, st.members);
    else if (ts.isTypeAliasDeclaration(st)) members = nestedMembers(p.sf, st.type, "");
    if (members.length) {
      lines.push(ts.isTypeAliasDeclaration(st) ? "Documented members:" : "Members:", "");
      for (const m of members) {
        const ref = !m.doc && m.node.type && ts.isTypeReferenceNode(m.node.type) && ts.isIdentifier(m.node.type.typeName) ? m.node.type.typeName.text : null;
        const body = m.doc?.lines.length ? docMarkdown(m.doc.lines, link) : ref && link.target(ref) ? `See ${link(ref)}.` : "";
        const dep2 = deprecatedMarkdown(m.doc, link);
        const tags = tagsMarkdown(m.doc, link);
        const text = [dep2, body, tags].filter(Boolean).join("\n\n");
        const indented = text.split("\n").map((l, i) => (i === 0 || !l ? l : `  ${l}`)).join("\n");
        lines.push(`- ${code(m.name)}${text ? `: ${indented}` : ""}`);
      }
      lines.push("");
    }
    const tags = tagsMarkdown(item.doc, link);
    if (tags) lines.push(tags, "");
    const uses = item.decls.flatMap((d) => typeRefs(d)).filter((n, i, a) => n !== item.name && a.indexOf(n) === i && link.target(n));
    if (uses.length) lines.push(`Uses: ${uses.map((n) => link(n)).join(", ")}.`, "");
    const users = (usedBy.get(item.name) ?? []).filter((u) => !(u.page === p.page && u.name === item.name));
    if (users.length) lines.push(`Used by: ${users.map((u) => `[${code(u.name)}](${u.page === p.page ? "" : u.page}#${u.anchor})`).join(", ")}.`, "");
    return lines.join("\n");
  };
  if (exported.length) out.push("## Declarations", "", ...exported.map(section));
  if (local.length) out.push("## Local types", "", "Not exported. They appear in the signatures above.", "", ...local.map(section));
  if (reexports.length) {
    out.push("## Re-exports", "");
    for (const r of reexports) out.push(`- ${link(r.name)} from \`${r.from}\``);
    out.push("");
  }
  return out.join("\n");
}

/// name → [{ page, name, anchor }] of the declarations that refer to it.
function usedByTable(pages, symbols) {
  const used = new Map();
  for (const p of pages) {
    for (const item of p.decl.items) {
      for (const ref of new Set(item.decls.flatMap((d) => typeRefs(d)))) {
        if (ref === item.name || !symbols.has(ref)) continue;
        if (!used.has(ref)) used.set(ref, []);
        used.get(ref).push({ page: p.page, name: item.name, anchor: item.anchor });
      }
    }
  }
  return used;
}

