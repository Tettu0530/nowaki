// Markdown helpers

/// GitHub's heading anchor: lowercase, punctuation other than "-" and "_" dropped, spaces to "-".
const slug = (heading) =>
  heading
    .toLowerCase()
    .replace(/`/g, "")
    .replace(/[^\p{L}\p{N}\s_-]/gu, "")
    .trim()
    .replace(/\s/g, "-");

const cell = (s) => s.replace(/\\/g, "\\\\").replace(/\|/g, "\\|").replace(/\n+/g, " ");
const code = (s) => (s.includes("`") ? `\`\` ${s} \`\`` : `\`${s}\``);

function table(head, rows) {
  return [`| ${head.join(" | ")} |`, `| ${head.map(() => "---").join(" | ")} |`, ...rows.map((r) => `| ${r.map(cell).join(" | ")} |`)].join("\n");
}

/// Escapes `<` outside code spans (so `<Link>` written without backticks isn't read as HTML) and
/// turns {@link Name} into a link through `link`.
function inline(text, link) {
  return text
    .split(/(`+[^`]*`+)/)
    .map((part, i) => {
      if (i % 2 === 1) return part;
      return part
        .replace(/\{@link\s+([^}\s|]+)(?:[\s|]+([^}]*))?\}/g, (_, name, label) => link(name, label?.trim()))
        .replace(/</g, "&lt;");
    })
    .join("");
}

