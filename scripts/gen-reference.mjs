// Declarations of a types file

const printer = ts.createPrinter({ removeComments: true, newLine: ts.NewLineKind.LineFeed });
const hasExport = (n) => (ts.getCombinedModifierFlags(n) & ts.ModifierFlags.Export) !== 0;

function parse(root, file) {
  return ts.createSourceFile(file, read(root, file), ts.ScriptTarget.Latest, true, ts.ScriptKind.TS);
}

/// Type names a node refers to (type references and `extends` clauses), in order of appearance.
function typeRefs(node) {
  const names = [];
  const visit = (n) => {
    if (ts.isTypeReferenceNode(n) && ts.isIdentifier(n.typeName)) names.push(n.typeName.text);
    if (ts.isExpressionWithTypeArguments(n) && ts.isIdentifier(n.expression)) names.push(n.expression.text);
    ts.forEachChild(n, visit);
  };
  visit(node);
  return [...new Set(names)];
}

function kindOf(st) {
  if (ts.isFunctionDeclaration(st)) return /^[A-Z]/.test(st.name.text) ? "component" : "function";
  if (ts.isClassDeclaration(st)) return "class";
  if (ts.isInterfaceDeclaration(st)) return "interface";
  if (ts.isTypeAliasDeclaration(st)) return "type";
  if (ts.isVariableStatement(st)) return "const";
  return null;
}

const KIND_LABEL = { component: "Component", function: "Function", class: "Class", interface: "Interface", type: "Type", const: "Constant" };

/// Members of a type with their JSDoc, recursing into object literal types (nested ones are listed
/// only when documented): [{ name, doc, node }].
function membersOf(sf, members, prefix = "", all = true) {
  const out = [];
  const seen = new Set();
  for (const m of members) {
    const name = m.name ? (ts.isIdentifier(m.name) || ts.isStringLiteral(m.name) ? m.name.text : m.name.getText(sf)) : null;
    if (ts.isConstructorDeclaration(m)) {
      out.push({ name: "constructor", doc: jsdoc(m, sf), node: m });
      continue;
    }
    if (!name) continue; // index signatures
    const doc = jsdoc(m, sf);
    const key = prefix + name;
    if (!seen.has(key) && (all || doc)) out.push({ name: key, doc, node: m });
    seen.add(key);
    if (m.type) out.push(...nestedMembers(sf, m.type, key));
  }
  return out;
}

function nestedMembers(sf, type, prefix) {
  if (ts.isTypeLiteralNode(type)) return membersOf(sf, type.members, prefix ? `${prefix}.` : "", false);
  if (ts.isArrayTypeNode(type)) return nestedMembers(sf, type.elementType, `${prefix}[]`);
  if (ts.isParenthesizedTypeNode(type)) return nestedMembers(sf, type.type, prefix);
  if (ts.isUnionTypeNode(type) || ts.isIntersectionTypeNode(type)) return type.types.flatMap((t) => nestedMembers(sf, t, prefix));
  return [];
}

/// Every declaration in a types file: [{ name, kind, exported, decls: [statement], doc }], plus
/// re-exports [{ name, from }] and the default export's name.
function declarations(sf) {
  const items = [];
  const byName = new Map();
  const reexports = [];
  let defaultExport = null;
  for (const st of sf.statements) {
    if (ts.isImportDeclaration(st)) continue;
    if (ts.isExportDeclaration(st)) {
      const from = st.moduleSpecifier?.text;
      for (const el of st.exportClause?.elements ?? []) reexports.push({ name: el.name.text, from, type: st.isTypeOnly || el.isTypeOnly });
      continue;
    }
    if (ts.isExportAssignment(st)) {
      defaultExport = st.expression.getText(sf);
      continue;
    }
    const kind = kindOf(st);
    if (!kind) continue;
    const names = ts.isVariableStatement(st) ? st.declarationList.declarations.map((d) => d.name.getText(sf)) : [st.name.text];
    for (const name of names) {
      const doc = jsdoc(st, sf);
      if (kind === "function" || kind === "component") {
        const prev = byName.get(name);
        if (prev) {
          prev.decls.push(st);
          prev.doc ??= doc;
          continue;
        }
      }
      const item = { name, kind, exported: hasExport(st), decls: [st], doc };
      byName.set(name, item);
      items.push(item);
    }
  }
  return { items, reexports, defaultExport };
}

