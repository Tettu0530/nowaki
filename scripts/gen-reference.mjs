/// Every page: Map file name → text.
export function generate(root = REPO) {
  const pages = typePages(root);
  const symbols = symbolTable(pages);
  const usedBy = usedByTable(pages, symbols);
  const files = new Map();
  files.set("README.md", renderIndex(root, pages));
  for (const p of pages) files.set(p.page, renderTypePage(p, symbols, usedBy));
  files.set("route-exports.md", renderRouteExports(root, pages, symbols));
  files.set("file-conventions.md", renderFiles(root));
  files.set("config.md", renderConfig(root, pages, symbols));
  files.set("cli.md", renderCli(root));
  files.set("env-vars.md", renderEnv(root));
  files.set("endpoints.md", renderEndpoints(root));
  files.set("headers.md", renderHeaders(root));
  files.set("client-events.md", renderClient(root));
  for (const [k, v] of files) files.set(k, v.replace(/\n{3,}/g, "\n\n").trimEnd() + "\n");
  checkLinks(root, files);
  return new Map([...files].sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0)));
}

function main(argv) {
  const check = argv.includes("--check");
  const dir = path.join(REPO, OUT_DIR);
  const files = generate(REPO);
  const present = existsSync(dir) ? readdirSync(dir).filter((f) => f.endsWith(".md")).sort() : [];
  const stale = [];
  for (const [name, text] of files) {
    const p = path.join(dir, name);
    const current = existsSync(p) ? normalize(readFileSync(p, "utf8")) : null;
    if (current !== text) stale.push(name);
  }
  const extra = present.filter((f) => !files.has(f));
  if (check) {
    if (stale.length || extra.length) {
      if (stale.length) console.error(`gen-reference: out of date: ${stale.map((f) => `${OUT_DIR}/${f}`).join(", ")}`);
      if (extra.length) console.error(`gen-reference: not generated (remove them): ${extra.map((f) => `${OUT_DIR}/${f}`).join(", ")}`);
      console.error("Run `node scripts/gen-reference.mjs` and commit the result (CONTRIBUTING.md > API reference).");
      process.exit(1);
    }
    console.log(`gen-reference: OK (${files.size} pages up to date)`);
    return;
  }
  mkdirSync(dir, { recursive: true });
  for (const name of stale) {
    writeFileSync(path.join(dir, name), files.get(name));
    console.log(`wrote ${OUT_DIR}/${name}`);
  }
  for (const name of extra) {
    unlinkSync(path.join(dir, name));
    console.log(`removed ${OUT_DIR}/${name}`);
  }
  if (!stale.length && !extra.length) console.log(`gen-reference: ${files.size} pages already up to date`);
}

const entry = process.argv[1] ? pathToFileURL(path.resolve(process.argv[1])).href : "";
if (import.meta.url === entry) {
  try {
    main(process.argv.slice(2));
  } catch (e) {
    console.error(e.message);
    process.exit(1);
  }
}
