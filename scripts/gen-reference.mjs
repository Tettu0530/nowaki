// "label: keys" where the label may hold "(provider: ...)".
const NESTED = /^((?:[^:(]|\([^)]*\))+):\s(.*)$/;

function renderConfig(root, pages, symbols) {
  const cfg = pages.find((p) => p.page === "runtime-config.md");
  const link = linker(symbols, "config.md");
  const entries = snapshot(root, "config.txt");
  const top = entries.filter((e) => e.title === "top-level").map((e) => e.text);
  const nested = entries.filter((e) => e.title === "nested").map((e) => e.text);
  const hooks = entries.filter((e) => e.title === "plugins").map((e) => e.text);
  const files = entries.filter((e) => e.title === "files" && !e.text.startsWith("export "));
  const item = cfg.decl.items.find((i) => i.name === "NowakiConfig");
  const members = membersOf(cfg.sf, item.decls[0].members).filter((m) => !m.name.includes("."));
  const memberNames = members.map((m) => m.name);
  const diff = (a, b) => a.filter((x) => !b.includes(x));
  if (diff(top, memberNames).length || diff(memberNames, top).length) {
    fail(`api/config.txt top-level keys (${top.join(", ")}) and NowakiConfig members (${memberNames.join(", ")}) differ`);
  }
  const plugin = cfg.decl.items.find((i) => i.name === "NowakiPlugin");
  const pluginMembers = membersOf(cfg.sf, plugin.decls[0].members).map((m) => m.name);
  if (diff(hooks, pluginMembers).length || diff(pluginMembers, hooks).length) {
    fail(`api/config.txt plugin hooks (${hooks.join(", ")}) and NowakiPlugin members (${pluginMembers.join(", ")}) differ`);
  }
  // Every nested key the validator accepts is a property somewhere in config.d.ts.
  const props = new Set();
  const visit = (n) => {
    if ((ts.isPropertySignature(n) || ts.isMethodSignature(n)) && n.name) props.add(n.name.getText(cfg.sf));
    ts.forEachChild(n, visit);
  };
  visit(cfg.sf);
  for (const line of nested) {
    const [, label, keys] = line.match(NESTED);
    if (label === "trailingSlash") continue;
    for (const k of keys.split(", ")) if (!props.has(k)) fail(`api/config.txt: ${label} key ${k} has no property in config.d.ts`);
  }

  const out = [
    NOTICE("`packages/nowaki-runtime/config.d.ts` and `api/config.txt`"),
    "",
    "# nowaki.config",
    "",
    `${GENERATED} The app's configuration file, read by \`nowaki dev\` and \`nowaki build\`.`,
    "",
    `File: ${files.map((f) => code(f.text)).join(" or ")} in the app root (the first one found), with the config as its default export.`,
    "",
    "```js",
    "// nowaki.config.mjs",
    'import { defineConfig } from "@nowaki-dev/runtime/config";',
    "",
    'export default defineConfig({ site: "https://example.com" });',
    "```",
    "",
    "An unknown key is an error at every level, with a \"did you mean\" hint. Types: [runtime-config.md](runtime-config.md).",
    "",
    "## Keys",
    "",
    table(
      ["Key", "Type", "Description"],
      members.map((m) => [
        `[${code(m.name)}](#${slug(m.name)})`,
        code(printer.printNode(ts.EmitHint.Unspecified, m.node.type, cfg.sf)),
        inline(summary(m.doc), link),
      ]),
    ),
    "",
  ];
  for (const m of members) {
    out.push(`### ${m.name}`, "", "```ts", `${m.name}?: ${printer.printNode(ts.EmitHint.Unspecified, m.node.type, cfg.sf)}`, "```", "");
    if (m.doc) out.push(docMarkdown(m.doc.lines, link), "");
    const keys = nested.filter((n) => n.split(/[:[. ]/)[0] === m.name);
    if (keys.length) {
      out.push(m.name === "trailingSlash" ? "Accepted values (from the validator):" : "Accepted keys (from the validator):", "");
      for (const k of keys) {
        const [, label, rest] = k.match(NESTED);
        out.push(`- ${code(label)}: ${rest.split(/, | \| /).map(code).join(k.includes(" | ") ? " \\| " : ", ")}`);
      }
      out.push("");
    }
    const refs = typeRefs(m.node.type).filter((n) => link.target(n));
    if (refs.length) out.push(`See ${refs.map((r) => link(r)).join(", ")}.`, "");
  }
  out.push("## Plugin hooks", "", `A plugin is an object with ${hooks.map(code).join(", ")}: see ${link("NowakiPlugin")}.`, "");
  return out.join("\n");
}

