// JSDoc

const TAGS = new Set(["example", "param", "returns", "deprecated", "see", "default"]);

/// The JSDoc comment right before `node`: { lines, tags: [{ tag, lines }] }, or null.
function jsdoc(node, sf) {
  const ranges = ts.getLeadingCommentRanges(sf.text, node.getFullStart()) ?? [];
  const r = ranges.filter((c) => sf.text.startsWith("/**", c.pos) && !sf.text.startsWith("/**/", c.pos)).pop();
  if (!r) return null;
  const body = sf.text.slice(r.pos + 3, r.end - 2);
  const lines = body.split("\n").map((l, i) => {
    const t = i === 0 ? l.replace(/^ /, "") : l.replace(/^\s*\* ?/, "").replace(/^\s*$/, "");
    return t.trimEnd().replace(/\*\\\//g, "*/");
  });
  while (lines.length && !lines[0].trim()) lines.shift();
  while (lines.length && !lines.at(-1).trim()) lines.pop();
  const doc = { lines: [], tags: [] };
  let cur = doc.lines;
  for (const l of lines) {
    const m = l.match(/^@(\w+)\b ?(.*)$/);
    if (m) {
      if (!TAGS.has(m[1])) fail(`${sf.fileName}: unknown JSDoc tag @${m[1]}; support it in scripts/gen-reference.mjs`);
      const t = { tag: m[1], lines: m[2] ? [m[2]] : [] };
      doc.tags.push(t);
      cur = t.lines;
    } else cur.push(l);
  }
  return doc;
}

/// JSDoc description lines to Markdown. A run of lines indented by two or more spaces that isn't
/// the continuation of a list item is a code sample and becomes a fenced block.
function docMarkdown(lines, link) {
  const out = [];
  let inList = false;
  for (let i = 0; i < lines.length; i++) {
    const l = lines[i];
    if (!l.trim()) {
      inList = false;
      out.push("");
      continue;
    }
    if (/^\s{2,}\S/.test(l) && !inList) {
      const run = [];
      while (i < lines.length && (/^\s{2,}\S/.test(lines[i]) || (!lines[i].trim() && /^\s{2,}\S/.test(lines[i + 1] ?? "")))) run.push(lines[i++]);
      i--;
      const indent = Math.min(...run.filter((x) => x.trim()).map((x) => x.match(/^\s*/)[0].length));
      if (out.length && out.at(-1) !== "") out.push("");
      out.push("```tsx", ...run.map((x) => x.slice(indent)), "```", "");
      continue;
    }
    if (/^([-*]|\d+\.) /.test(l)) inList = true;
    else if (!/^\s/.test(l)) inList = false;
    out.push(inline(l, link));
  }
  return out.join("\n").replace(/\n{3,}/g, "\n\n").trim();
}

/// First sentence of the description, on one line (for summary tables).
function summary(doc) {
  if (!doc) return "";
  const para = [];
  for (const l of doc.lines) {
    if (!l.trim() || /^\s{2,}/.test(l) || /^[-|]/.test(l)) break;
    para.push(l.trim());
  }
  const text = para.join(" ");
  let tick = false;
  for (let i = 0; i < text.length; i++) {
    if (text[i] === "`") tick = !tick;
    else if (!tick && text[i] === "." && (i + 1 === text.length || text[i + 1] === " ") && !/\b(e\.g|i\.e)$/.test(text.slice(0, i))) return text.slice(0, i + 1);
  }
  return text;
}

function tagsMarkdown(doc, link) {
  if (!doc) return "";
  const out = [];
  const by = (t) => doc.tags.filter((x) => x.tag === t);
  const params = by("param");
  if (params.length) {
    out.push("Parameters:", "");
    for (const p of params) {
      const [, name, rest] = p.lines.join("\n").match(/^(?:\{[^}]*\}\s*)?(\S+)\s*(?:-\s*)?([\s\S]*)$/) ?? [];
      out.push(`- \`${name}\`: ${inline(rest.replace(/\n/g, " "), link)}`);
    }
    out.push("");
  }
  for (const r of by("returns")) out.push(`Returns: ${inline(r.lines.join(" "), link)}`, "");
  for (const d of by("default")) out.push(`Default: ${inline(d.lines.join(" "), link)}`, "");
  for (const s of by("see")) out.push(`See: ${inline(s.lines.join(" "), link)}`, "");
  const examples = by("example");
  if (examples.length) {
    out.push(examples.length === 1 ? "Example:" : "Examples:", "");
    for (const e of examples) out.push("```tsx", ...e.lines, "```", "");
  }
  return out.join("\n").trim();
}

function deprecatedMarkdown(doc, link) {
  const d = doc?.tags.find((t) => t.tag === "deprecated");
  return d ? `> **Deprecated.** ${inline(d.lines.join(" "), link)}` : "";
}

