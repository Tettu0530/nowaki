// The API reference in docs/reference/, generated from the sources of truth:
// - the .d.ts files of @nowaki-dev/runtime and @nowaki-dev/markdoc (declarations and their JSDoc),
//   read with the TypeScript compiler API like scripts/api-surface.mjs;
// - the api/*.txt snapshots (route exports, file conventions, config keys, CLI flags, environment
//   variables, endpoints, headers, cookies, client events), which CI keeps in step with the code;
// - a few constants read from the code (default security headers, the CSP policy, create-nowaki
//   templates);
// - scripts/gen-reference-data.mjs for descriptions the source has no doc comment for.
//
//   node scripts/gen-reference.mjs           write docs/reference/*.md
//   node scripts/gen-reference.mjs --check   fail when docs/reference/ is out of date (CI)
//
// Generation fails when a stable name has no description, when a description names something that
// no longer exists, when the snapshots and the types disagree (a config key or route export missing
// from its type), or when a generated page links to an anchor no page has. Output is deterministic:
// "\n" line endings, declarations in source order, everything else sorted or in snapshot order.

