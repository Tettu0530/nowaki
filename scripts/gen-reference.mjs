const OUT_DIR = "docs/reference";
const normalize = (s) => s.replace(/\r\n?/g, "\n");
const read = (root, file) => normalize(readFileSync(path.join(root, file), "utf8"));

const NOTICE = (sources) =>
  `<!-- Generated by scripts/gen-reference.mjs from ${sources}. Do not edit by hand: change the source and run \`node scripts/gen-reference.mjs\`. -->`;
const GENERATED = "Generated from the source by `scripts/gen-reference.mjs`; do not edit by hand.";

// ---------------------------------------------------------------------------------------------
// api/*.txt snapshots

const COMMENT = /\s{2,}#\s.*$|\s{2,}#$/;

/// Entries of a snapshot: [{ status, title, text, comment }], in file order.
function snapshot(root, file) {
  const out = [];
  let section = null;
  for (const raw of read(root, `api/${file}`).split("\n")) {
    const line = raw.trimEnd();
    if (!line.trim() || line.trimStart().startsWith("#")) continue;
    const h = line.match(/^\[(\S+)(?:\s+(.+))?\]$/);
    if (h) {
      section = { status: h[1], title: h[2] ?? "" };
      continue;
    }
    const comment = line.match(COMMENT)?.[0].replace(/^\s+#\s?/, "") ?? "";
    out.push({ ...section, text: line.replace(COMMENT, "").trim(), comment });
  }
  return out;
}

const fail = (msg) => {
  throw new Error(`gen-reference: ${msg}`);
};

/// Checks that `data` describes exactly the `names` (no missing, no stale keys).
function described(data, names, what) {
  const missing = names.filter((n) => !Object.hasOwn(data, n));
  const stale = Object.keys(data).filter((k) => !names.includes(k));
  if (missing.length) fail(`no description for ${what} ${missing.join(", ")}; add it to scripts/gen-reference-data.mjs`);
  if (stale.length) fail(`scripts/gen-reference-data.mjs describes ${what} ${stale.join(", ")}, which the snapshot doesn't list; remove or rename it`);
}

