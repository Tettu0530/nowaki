//! Typed route generation. Writes `.nowaki/types.d.ts` (augmenting `NowakiRoutes`) from `routes/`
//! to make `route()` / `Link` type-safe. Also runs automatically on dev startup, routes changes, and build.

use std::path::Path;

use anyhow::{Context, Result};

fn render(routes: &[(String, String)]) -> String {
    let mut s = String::new();
    s.push_str("// AUTO-GENERATED by `nowaki typegen` — do not edit.\n");
    s.push_str("// Typed routes for @nowaki-dev/runtime/navigation (route() / <Link>).\n");
    s.push_str("import \"@nowaki-dev/runtime/navigation\";\n\n");
    s.push_str("declare module \"@nowaki-dev/runtime/navigation\" {\n");
    s.push_str("  interface NowakiRoutes {\n");
    for (path, params) in routes {
        s.push_str(&format!("    \"{path}\": {params};\n"));
    }
    s.push_str("  }\n}\n");
    s
}

/// Content collections: `Collections` gets one key per content/ sub-directory, typed by the
/// output of that collection's schema in content/config.
fn render_content(root: &Path) -> String {
    let config = ["config.ts", "config.mts", "config.js", "config.mjs"]
        .into_iter()
        .find(|f| root.join("content").join(f).is_file());
    let Some(config) = config else {
        return String::new();
    };
    let mut names: Vec<String> = std::fs::read_dir(root.join("content"))
        .into_iter()
        .flatten()
        .flatten()
        .filter(|e| e.path().is_dir())
        .filter_map(|e| e.file_name().to_str().map(str::to_string))
        .filter(|n| !n.starts_with('.') && !n.starts_with('_'))
        .collect();
    names.sort();
    let mut s = String::new();
    s.push_str(
        "\n// Content collections for @nowaki-dev/runtime/content (getCollection / getEntry).\n",
    );
    s.push_str("import type { CollectionData } from \"@nowaki-dev/runtime/content\";\n");
    s.push_str(&format!(
        "type NowakiContentConfig = typeof import(\"../content/{config}\");\n\n"
    ));
    s.push_str("declare module \"@nowaki-dev/runtime/content\" {\n");
    s.push_str("  interface Collections {\n");
    for n in names {
        s.push_str(&format!(
            "    {:?}: CollectionData<NowakiContentConfig[{:?}]>;\n",
            n, n
        ));
    }
    s.push_str("  }\n}\n");
    s
}

/// Skip the write if unchanged (avoids needlessly triggering the dev file watcher).
pub fn write(root: &Path) -> Result<()> {
    let routes_dir = root.join("routes");
    if !routes_dir.is_dir() {
        return Ok(());
    }
    let routes = nowaki_core::routes::scan_typegen(&routes_dir)?;
    let out_dir = root.join(".nowaki");
    std::fs::create_dir_all(&out_dir)
        .with_context(|| format!("failed to create: {}", out_dir.display()))?;
    let content = render(&routes) + &render_content(root);
    let path = out_dir.join("types.d.ts");
    if std::fs::read_to_string(&path).ok().as_deref() != Some(content.as_str()) {
        std::fs::write(&path, &content)
            .with_context(|| format!("failed to write: {}", path.display()))?;
    }
    Ok(())
}

pub fn run(root: std::path::PathBuf) -> Result<()> {
    let routes_dir = root.join("routes");
    if !routes_dir.is_dir() {
        anyhow::bail!("routes/ not found ({}).", root.display());
    }
    let n = nowaki_core::routes::scan_typegen(&routes_dir)?.len();
    write(&root)?;
    println!(
        "{} {} route(s) → {}",
        crate::ui::green("✓ typegen"),
        n,
        crate::ui::dim(".nowaki/types.d.ts")
    );
    Ok(())
}

#[cfg(test)]
mod tests {
    #[test]
    fn render_emits_module_augmentation() {
        let out = super::render(&[
            ("/".into(), "{}".into()),
            ("/blog/[slug]".into(), "{ slug: string }".into()),
        ]);
        assert!(out.contains("declare module \"@nowaki-dev/runtime/navigation\""));
        assert!(out.contains("\"/\": {};"));
        assert!(out.contains("\"/blog/[slug]\": { slug: string };"));
    }
}
