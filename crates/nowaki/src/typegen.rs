//! Typed route generation: writes `.nowaki/types.d.ts` (`NowakiRoutes` from `routes/` for
//! `route()` / `<Link>`, plus content collections and env.ts types). Besides `nowaki typegen`, every
//! `nowaki build` (the static adapter too) runs it, and `nowaki dev` at startup and when routes or
//! content change.

use std::path::Path;

use anyhow::{Context, Result};

fn render(routes: &[(String, String)]) -> String {
    let mut s = String::new();
    s.push_str("// AUTO-GENERATED by `nowaki typegen` — do not edit.\n");
    s.push_str("// Typed routes for @nowaki-dev/runtime/navigation (route() / <Link>).\n");
    s.push_str("import \"@nowaki-dev/runtime/navigation\";\n\n");
    s.push_str("declare module \"@nowaki-dev/runtime/navigation\" {\n");
    s.push_str("  interface NowakiRoutes {\n");
    for (path, params) in routes {
        s.push_str(&format!("    \"{path}\": {params};\n"));
    }
    s.push_str("  }\n}\n");
    s
}

/// Content collections: `Collections` gets one key per content/ sub-directory, typed by the
/// output of that collection's schema in content/config.
fn render_content(root: &Path) -> String {
    let config = ["config.ts", "config.mts", "config.js", "config.mjs"]
        .into_iter()
        .find(|f| root.join("content").join(f).is_file());
    let Some(config) = config else {
        return String::new();
    };
    let mut names: Vec<String> = std::fs::read_dir(root.join("content"))
        .into_iter()
        .flatten()
        .flatten()
        .filter(|e| e.path().is_dir())
        .filter_map(|e| e.file_name().to_str().map(str::to_string))
        .filter(|n| !n.starts_with('.') && !n.starts_with('_'))
        .collect();
    names.sort();
    let mut s = String::new();
    s.push_str(
        "\n// Content collections for @nowaki-dev/runtime/content (getCollection / getEntry).\n",
    );
    s.push_str("import type { CollectionData } from \"@nowaki-dev/runtime/content\";\n");
    s.push_str(&format!(
        "type NowakiContentConfig = typeof import(\"../content/{config}\");\n\n"
    ));
    s.push_str("declare module \"@nowaki-dev/runtime/content\" {\n");
    s.push_str("  interface Collections {\n");
    for n in names {
        s.push_str(&format!(
            "    {:?}: CollectionData<NowakiContentConfig[{:?}]>;\n",
            n, n
        ));
    }
    s.push_str("  }\n}\n");
    s
}

/// env.ts: `ServerEnv` (`@nowaki-dev/runtime/env/server`) and `ImportMetaEnv` (the public values)
/// typed by the output of each variable's schema.
fn render_env(root: &Path) -> String {
    let Some(file) = nowaki_core::env::env_file(root) else {
        return String::new();
    };
    let name = file
        .file_name()
        .and_then(|n| n.to_str())
        .unwrap_or("env.ts");
    let mut s = String::new();
    s.push_str("\n// Environment from env.ts (@nowaki-dev/runtime/env/server, import.meta.env).\n");
    s.push_str("import type { PublicEnvOf, ServerEnvOf } from \"@nowaki-dev/runtime/env\";\n");
    s.push_str(&format!(
        "type NowakiEnvDefinition = typeof import(\"../{name}\").default;\n\n"
    ));
    s.push_str("declare module \"@nowaki-dev/runtime/env/server\" {\n");
    s.push_str("  interface ServerEnv extends ServerEnvOf<NowakiEnvDefinition> {}\n}\n\n");
    s.push_str("declare global {\n");
    s.push_str("  interface ImportMetaEnv extends PublicEnvOf<NowakiEnvDefinition> {}\n");
    s.push_str("  interface ImportMeta {\n    readonly env: ImportMetaEnv;\n  }\n}\n");
    s
}

/// Writes `.nowaki/types.d.ts` (nothing without `routes/`). An unchanged file is not rewritten, so
/// the dev file watcher doesn't fire for it.
pub fn write(root: &Path) -> Result<()> {
    let routes_dir = root.join("routes");
    if !routes_dir.is_dir() {
        return Ok(());
    }
    let routes = nowaki_core::routes::scan_typegen(&routes_dir)?;
    let out_dir = root.join(".nowaki");
    std::fs::create_dir_all(&out_dir)
        .with_context(|| format!("failed to create: {}", out_dir.display()))?;
    let content = render(&routes) + &render_content(root) + &render_env(root);
    let path = out_dir.join("types.d.ts");
    if std::fs::read_to_string(&path).ok().as_deref() != Some(content.as_str()) {
        std::fs::write(&path, &content)
            .with_context(|| format!("failed to write: {}", path.display()))?;
    }
    Ok(())
}

/// `nowaki typegen`: [`write()`], then a one-line summary; fails without `routes/`.
pub fn run(root: std::path::PathBuf) -> Result<()> {
    let routes_dir = root.join("routes");
    if !routes_dir.is_dir() {
        anyhow::bail!("routes/ not found ({}).", root.display());
    }
    let n = nowaki_core::routes::scan_typegen(&routes_dir)?.len();
    write(&root)?;
    println!(
        "{} {} route(s) → {}",
        crate::ui::green("✓ typegen"),
        n,
        crate::ui::dim(".nowaki/types.d.ts")
    );
    Ok(())
}

#[cfg(test)]
mod tests {
    #[test]
    fn render_emits_module_augmentation() {
        let out = super::render(&[
            ("/".into(), "{}".into()),
            ("/blog/[slug]".into(), "{ slug: string }".into()),
        ]);
        assert!(out.contains("declare module \"@nowaki-dev/runtime/navigation\""));
        assert!(out.contains("\"/\": {};"));
        assert!(out.contains("\"/blog/[slug]\": { slug: string };"));
    }

    #[test]
    fn render_env_types_server_and_public_values() {
        let dir = std::env::temp_dir().join(format!("nowaki-typegen-env-{}", std::process::id()));
        std::fs::create_dir_all(&dir).unwrap();
        assert_eq!(super::render_env(&dir), "");
        std::fs::write(dir.join("env.ts"), "").unwrap();
        let out = super::render_env(&dir);
        assert!(out.contains("typeof import(\"../env.ts\").default"));
        assert!(out.contains("interface ServerEnv extends ServerEnvOf<NowakiEnvDefinition> {}"));
        assert!(out.contains("interface ImportMetaEnv extends PublicEnvOf<NowakiEnvDefinition> {}"));
        std::fs::remove_dir_all(&dir).ok();
    }
}
